import { SONG_PARTS } from './song-parts.js';

const rest = (bars) => '-'.repeat(bars * 16);
/** 分轨里那条轨道的音 */
const loopNotes = (id, track) => SONG_PARTS[id].parts.find((p) => p.track === track).notes;
/** 整条乐句的音都移 d 个八度（完整版改了这条轨道的 OCTAVE，分轨里那段要反过来移回原来的音高） */
const shiftOct = (notes, d) => notes.map(([st, k, len = 1, sh = 0]) => (sh + d ? [st, k, len, sh + d] : [st, k, len]));
/** 每小节一样的节奏型（[第几步 0 起, 几步长]），一小节换一个键 */
const groove = (rhythm, keys, octShift = 0) => keys.flatMap((k, bar) => rhythm.map(([st, len]) => (octShift ? [bar * 16 + st, k, len, octShift] : [bar * 16 + st, k, len])));
/** 每半小节一个和弦，按同一个扫弦节奏（[第几步 0–7, 几步长]）敲；swap = { 第几个半小节（0 起）: [[步, 键, 长]…] } 换掉那半小节 */
const strum = (rhythm, chords, swap = {}) => chords.flatMap((k, half) => swap[half] ?? rhythm.map(([st, len]) => [half * 8 + st, k, len]));
/** 第几小节（1 起）在第 after 步之后急停：那几小节里 after 步以后的音去掉，跨过去的截短 */
const stopAfter = (notes, barList, after) => notes.flatMap(([st, k, len = 1, sh]) => {
  const b = Math.floor(st / 16) + 1, i = st % 16;
  if (!barList.includes(b)) return [[st, k, len, sh]];
  if (i >= after) return [];
  return [[st, k, Math.min(len, after - i), sh]];
}).map((n) => (n[3] ? n : n.slice(0, 3)));

// 一条分轨里只留第 from–to 小节（1 起，含）的音：做“这几小节空着 / 急停”的那一版
const keepBars = (notes, from, to) => notes.filter(([s]) => s >= (from - 1) * 16 && s < to * 16);
// 每小节一样的鼓型重复几遍；某几小节换成别的（{ 第几小节（1 起）: 那一小节的串 }）
const bars = (n, bar, swap = {}) => Array.from({ length: n }, (_, i) => swap[i + 1] ?? bar).join('');

