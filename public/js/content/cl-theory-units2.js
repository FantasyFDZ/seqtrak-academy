/** 一串音（第几级）排进格子：每个占 unit 格；'-' = 把前一个音再拉长 unit 格；null = 空 unit 格。从第 at 格排起 */
const M = (degs, unit = 2, at = 0) => {
  const out = [];
  let s = at;
  for (const d of degs) {
    if (d === '-') out[out.length - 1][1] += unit;
    else if (d !== null) out.push([s, unit, d]);
    s += unit;
  }
  return out;
};
/** 一串和弦（第几级）排进格子：每个占 len 格 */
const C = (degs, len = 4, at = 0) => degs.map((d, i) => [at + i * len, len, d]);

