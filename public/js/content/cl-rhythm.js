const FOUR = 'x---x---x---x---';
const BACK = '----x-------x---';
const EIGHTS = 'x-x-x-x-x-x-x-x-';
const OFF = '--x---x---x---x-';
const GAP_E = '-x---x---x---x--'; // 每拍的第 2 格（“e”）
