// R2 挑战要点、要打的那一小节：铜 / 银 / 金各一条（自己编的；每拍的切法越往后越绕，银、金带三格的长音）
const R2_BARS = ['x-x-xxxxx-x-xxxx', 'x--xx-xxx-x-x--x', 'x-xxx--xxx-xx---'];
// R7 在挪的那只手：半小节一下，每条往后挪一格（一格 = 半拍 = 两个方键），每条连打两遍；不动的那只手是 FOUR（每拍一下）
const R7_MOVES = ['x-------x-------', '--x-------x-----', '----x-------x---', '------x-------x-'].flatMap((p) => [p, p]).join('');
const R7_BARS = 8;
/** R7 的一段：fixed = 不动的那只手是哪条轨道；hat = 带不带八分的镲伴奏（金那一档不带，只剩节拍器） */
const r7chart = (id, fixed, hat) => ({
  id, bpm: 88, bars: R7_BARS, loops: 1,
  lanes: { KICK: fixed === 'KICK' ? FOUR.repeat(R7_BARS) : R7_MOVES, SNARE: fixed === 'SNARE' ? FOUR.repeat(R7_BARS) : R7_MOVES },
  ...(hat ? { backing: { HAT1: EIGHTS.repeat(R7_BARS) } } : {}),
});

// R10 不出声的那一拍。row([步, …]) = 这几步有音的一小节；hush(这一小节有哪几步, 其中哪几步是灰的) = 一小节的 [要打的, 灰的]
const row = (steps) => Array.from({ length: 16 }, (_, i) => (steps.includes(i) ? 'x' : '-')).join('');
const hush = (all, grey) => [row(all.filter((s) => !grey.includes(s))), row(grey)];
const BEATS4 = [0, 4, 8, 12]; // 每拍一下
const CELLS8 = [0, 2, 4, 6, 8, 10, 12, 14]; // 一拍两下
/** “灰的别按”的一段：bars = [[要打的, 灰的], …]，每一小节连打两遍；底鼓每拍一下替你数着 */
const hushChart = (id, bars) => {
  const twice = bars.flatMap((b) => [b, b]);
  return { id, bpm: 92, bars: twice.length, loops: 1, lanes: { HAT1: twice.map((b) => b[0]).join('') }, rests: { HAT1: twice.map((b) => b[1]).join('') }, backing: { KICK: FOUR.repeat(twice.length) } };
};
// 三档：铜每拍一下、空一拍；银一拍两下、每小节空两下；金空三下（三、三、二的位置），每条往后挪一格
const HUSH_TIERS = [
  hushChart('r10-hush-1', [hush(BEATS4, [8]), hush(BEATS4, [4]), hush(BEATS4, [0])]),
  hushChart('r10-hush-2', [hush(CELLS8, [4, 12]), hush(CELLS8, [6, 14]), hush(CELLS8, [0, 8])]),
  hushChart('r10-hush-3', [hush(CELLS8, [0, 6, 12]), hush(CELLS8, [2, 8, 14]), hush(CELLS8, [4, 10, 0])]),
];
/** “静一小节，准点回来”的一段：plan 里 P = 照常打的一小节（每拍一下），Q = 整小节没声音（四下都是灰的） */
const quietChart = (id, plan) => ({
  chart: {
    id, bpm: 92, bars: plan.length, loops: 1,
    lanes: { HAT1: [...plan].map((c) => (c === 'P' ? FOUR : '-'.repeat(16))).join('') },
    rests: { HAT1: [...plan].map((c) => (c === 'Q' ? FOUR : '-'.repeat(16))).join('') },
    backing: { KICK: FOUR.repeat(plan.length), CLAP: BACK.repeat(plan.length) },
  },
  // 一段连着的 Q 是一段“静”：[从第几拍, 到第几拍]
  quiet: [...plan.matchAll(/Q+/g)].map((m) => [m.index * 4, (m.index + m[0].length) * 4]),
});

